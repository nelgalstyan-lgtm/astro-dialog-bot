def _date_in_range(month: int, day: int, start, end) -> bool:
    (m1, d1), (m2, d2) = start, end
    if m1 <= m2:
        return (m1, d1) <= (month, day) <= (m2, d2)
    return (month, day) >= (m1, d1) or (month, day) <= (m2, d2)


def get_decan_archetypes(zodiac_key: str, month: int, day: int):
    """Возвращает список из 4 id архетипов декана, в который попадает дата,
    либо None, если у знака деканы не заданы."""
    decans = ZODIAC[zodiac_key].get("decans")
    if not decans:
        return None
    for group in decans:
        if _date_in_range(month, day, *group["range"]):
            return group["archetypes"]
    return None


def get_profile_type(
    zodiac_key: str,
    type_id: str | None = None,
    month: int | None = None,
    day: int | None = None,
    hour: int | None = None,
    minute: int | None = None,
):
    """Возвращает психотип пользователя.

    Логика (детерминированная — один и тот же человек всегда получает один
    и тот же архетип):
    1. Если явно передан type_id — возвращаем именно его.
    2. Если у знака заданы деканы (три периода по 4 архетипа) — сначала
       находим декан по дате рождения, затем внутри декана выбираем один
       из 4 архетипов по формуле:
         index = (day + hour + minute) % 4   — если известно время рождения;
         index = day % 4                       — если время рождения неизвестно
                                                   (в анкете оно необязательно).
    3. Если у знака нет деканов (или дата не передана) — возвращаем
       единственный доступный архетип знака.
    """
    types_list = get_all_types(zodiac_key)
    if type_id:
        for t in types_list:
            if t["id"] == type_id:
                return t

    if month is not None and day is not None:
        archetype_ids = get_decan_archetypes(zodiac_key, month, day)
        if archetype_ids:
            if hour is not None and minute is not None:
                index = (day + hour + minute) % len(archetype_ids)
            else:
                index = day % len(archetype_ids)
            chosen_id = archetype_ids[index]
            for t in types_list:
                if t["id"] == chosen_id:
                    return t

    return types_list[0]


def get_zodiac_by_date(day: int, month: int):
    """Возвращает key знака зодиака по дню и месяцу рождения."""
    for key, data in ZODIAC.items():
        (m_from, d_from), (m_to, d_to) = data["range"]
        if m_from <= m_to:
            start = (m_from, d_from)
            end = (m_to, d_to)
            if start <= (month, day) <= end:
                return key
        else:
            # Диапазон через новый год (Козерог: 22 декабря — 19 января)
            if (month, day) >= (m_from, d_from) or (month, day) <= (m_to, d_to):
                return key
    return None
